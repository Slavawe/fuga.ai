#!/usr/bin/env python3
"""Бесконечный тюремный заговор — стратегия + VSA-учитель.

Задача: счётное бесконечное множество заключённых, каждый видит
все колпаки кроме своего. Черный/белый. Должны угадать СВОЙ цвет
одновременно. Могут договориться заранее.

РЕШЕНИЕ (аксиома выбора):
  1. Отношение эквивалентности: последовательности колпаков
     эквивалентны, если отличаются в КОНЕЧНОМ числе позиций.
  2. Аксиома выбора: из каждого класса выбираем представителя r(C).
  3. Заключённый n видит все колпаки кроме своего → знает класс C
     полной последовательности (свой колпак меняет ≤ 1 позицию,
     класс не меняется).
  4. Заключённый n угадывает r(C)_n — цвет из представителя.
  5. Фактическая последовательность и r(C) отличаются в конечном
     числе позиций → ВСЕ кроме конечного числа угадывают верно.

Модель (учитель-ученик):
  Учитель знает стратегию (аксиома выбора), ученик выдвигает
  гипотезы, учитель верифицирует через VSA-косинус.
  Симуляция конечного приближения доказывает: ≥ N−k верных.
"""

import sys
import json

